import * as QuickActions from 'expo-quick-actions';
import type { Href, useRouter } from 'expo-router';
import { AppState, Platform } from 'react-native';

import i18n from '../i18n';
import { getEvent, listEvents } from '../storage/events';
import { loadPreferences } from '../storage/preferences';
import { formatCivilDateMonthDay } from '../utils/calendars';
import { getNextOccurrence } from '../utils/recurrence';

// The shortcuts shown when the app icon is long-pressed (Android and
// iOS): New event, the next two upcoming events, and Overview. Set from
// JS (not static config) so they're translated and always current. On
// Android each one can also be dragged onto the home screen.

const UPCOMING_COUNT = 2;

// iOS uses SF Symbols; Android the drawables generated by the
// expo-quick-actions plugin from assets/shortcut-*.png (see app.json).
const ICONS =
  Platform.OS === 'ios'
    ? { add: 'symbol:plus.circle', event: 'symbol:calendar', overview: 'symbol:chart.bar' }
    : { add: 'shortcut_add', event: 'shortcut_event', overview: 'shortcut_overview' };

type Params = { href: string; eventId?: string };

type Router = ReturnType<typeof useRouter>;

let lastSet = '';

/** Rebuilds the shortcut list. Only while the app is in the foreground —
 *  the native side needs the current activity — and only when it changed. */
export async function syncAppShortcuts(): Promise<void> {
  if (AppState.currentState !== 'active') return;
  try {
    const [events, prefs] = await Promise.all([listEvents(), loadPreferences()]);
    const now = new Date();
    const upcoming = events
      .map((event) => ({ event, at: getNextOccurrence(event.dateTimeISO, event.repeat) }))
      .filter(({ at }) => at.isAfter(now))
      .sort((a, b) => a.at.valueOf() - b.at.valueOf())
      .slice(0, UPCOMING_COUNT);

    const items: QuickActions.Action[] = [
      { id: 'new-event', title: i18n.t('shortcuts.newEvent'), icon: ICONS.add, params: { href: '/event/new' } satisfies Params },
      ...upcoming.map(({ event, at }) => ({
        id: `event-${event.id}`,
        title: event.title,
        // iOS shows it under the title; Android has no subtitle.
        subtitle: formatCivilDateMonthDay(at.toISOString(), prefs.calendar, i18n.language),
        icon: ICONS.event,
        params: { href: `/event/${event.id}`, eventId: event.id } satisfies Params,
      })),
      { id: 'overview', title: i18n.t('shortcuts.overview'), icon: ICONS.overview, params: { href: '/overview' } satisfies Params },
    ];

    const key = JSON.stringify(items);
    if (key === lastSet) return;
    await QuickActions.setItems(items);
    lastSet = key;
  } catch {
    // Not supported on this launcher / no activity right now — the next
    // sync tries again.
  }
}

/** Opens what a shortcut points at. An event shortcut pinned to the
 *  Android home screen can outlive its event; then it opens the list. */
export async function openShortcut(action: QuickActions.Action, router: Router): Promise<void> {
  const params = action.params as Params | null | undefined;
  if (!params?.href) return;
  if (params.eventId && !(await getEvent(params.eventId))) {
    router.navigate('/');
    return;
  }
  router.navigate(params.href as Href);
}
